// Writes sim-builtin-boards.js: the built-in race tracks that have an online
// board (every track in tracks/catalog.json on a public map, sim-tracks.js
// PUBLIC_MAPS), with their gates, so the leaderboard Worker (which bundles
// that module, not the track files) checks a run against the track's own
// geometry, never one a client sent.
//
//   node tools/build_builtin_boards.mjs           (prints the module)
//   node tools/build_builtin_boards.mjs --write   (writes sim-builtin-boards.js)
//   node tools/build_builtin_boards.mjs --check   (exit 1 when it is stale)
//
// tools/test_leaderboard_builtin_boards.mjs fails when the module and the
// track files differ. A track's geometry is part of its board key
// (sim-retention.js builtinBoardKey), so an edit to one of these tracks starts
// that track's boards clean once the Worker with the new module is deployed.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PUBLIC_MAPS } from '../sim-tracks.js';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
export const BUILTIN_BOARDS_FILE = join(root, 'sim-builtin-boards.js');

const num = (v) => (Number.isFinite(+v) ? +v : 0);

export function builtinBoardTracks() {
  const catalog = JSON.parse(readFileSync(join(root, 'tracks', 'catalog.json'), 'utf8'));
  const out = [];
  for (const entry of catalog.tracks) {
    if (!PUBLIC_MAPS.includes(entry.map)) continue;
    if (entry.legacyId != null) continue; // the city loops: three laps, not on a public map
    const t = JSON.parse(readFileSync(join(root, entry.file), 'utf8'));
    if (t.id !== entry.id) throw new Error(entry.file + ': id ' + t.id + ' is not ' + entry.id);
    out.push({
      id: t.id,
      map: t.map,
      name: t.name,
      start: t.start ? { x: num(t.start.x), y: num(t.start.y), z: num(t.start.z) } : null,
      gates: t.gates.map((g) => ({ x: num(g.x), y: num(g.y), z: num(g.z), ry: num(g.ry), size: num(g.size), solid: !!g.solid })),
    });
  }
  return out;
}

export function builtinBoardsModule() {
  const tracks = builtinBoardTracks();
  return [
    '// SPDX-License-Identifier: GPL-3.0-or-later. Part of the QuadMath simulator; see SIM-NOTICE.txt.',
    '// Generated by tools/build_builtin_boards.mjs from tracks/*.json: do not edit.',
    '// The built-in race tracks with an online board (the public maps\' tracks),',
    '// with the gates the leaderboard Worker checks a run against.',
    'export const BUILTIN_BOARD_TRACKS = Object.freeze(' + JSON.stringify(tracks, null, 2) + ');',
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = builtinBoardsModule();
  if (process.argv.includes('--write')) {
    writeFileSync(BUILTIN_BOARDS_FILE, text);
    console.log('wrote ' + BUILTIN_BOARDS_FILE + ' (' + builtinBoardTracks().map((t) => t.id).join(', ') + ')');
  } else if (process.argv.includes('--check')) {
    const have = readFileSync(BUILTIN_BOARDS_FILE, 'utf8').replace(/\r\n/g, '\n');
    if (have !== text) { console.error('sim-builtin-boards.js is stale: node tools/build_builtin_boards.mjs --write'); process.exit(1); }
    console.log('sim-builtin-boards.js is current');
  } else {
    process.stdout.write(text);
  }
}
