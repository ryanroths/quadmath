// Flies the Rig's six coach lines on the bf core (tools/coach_rig_pilot.mjs)
// and prints each time; with --write, writes sim-coach-lines.js (the medal
// times and the ghost ribbons the page ships). Run it again after a change
// to the Rig, a drill's gates or the vendored sim-core, then stamp:
//   node tools/fly_coach_rig.mjs --write
//   python scripts/ci/stamp_asset_cache.py
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { rigCore, flyDrill, PLANS } from './coach_rig_pilot.mjs';
import { samplesToGhost, DRILLS } from '../sim-coach.js';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const coreVersion = readFileSync(join(root, 'vendor/sim-core/VERSION'), 'utf8').trim();

// A flown line as sim-coach-lines.js holds it: ms (lift-off to the last
// gate, rounded up), each gate's split, and the ribbon from the lift.
export function lineOf(flight) {
  const r = flight.result;
  const from = flight.samples.filter((s) => s.t >= r.lift && s.t <= r.lift + r.time + 0.05);
  const ghost = samplesToGhost(from.map((s) => ({ ...s, t: s.t - r.lift })));
  return {
    ms: Math.ceil(r.time * 1000),
    splits: r.splits.map((s) => Math.round(s * 1000)),
    line: ghost.map((g) => [Math.max(0, g[0]), g[1], g[2], g[3]]),
  };
}

export async function flyAll() {
  const core = await rigCore();
  const out = {};
  for (const d of DRILLS.filter((x) => x.chain)) {
    const f = await flyDrill(d.id, PLANS[d.id], { core });
    if (!f.result.done) throw new Error(d.id + ': the line did not finish (' + f.result.passes + '/' + f.result.gates + ' gates)');
    if (f.contacts.length) throw new Error(d.id + ': the line touched the Rig ' + f.contacts.length + ' times');
    out[d.id] = { flight: f, line: lineOf(f) };
  }
  return out;
}

function moduleText(lines) {
  const rows = Object.entries(lines).map(([id, l]) => {
    const pts = l.line.map((p) => '[' + p.join(', ') + ']').join(',\n      ');
    return `  '${id}': Object.freeze({\n    ms: ${l.ms},\n    splits: Object.freeze([${l.splits.join(', ')}]),\n    line: Object.freeze([\n      ${pts},\n    ]),\n  }),`;
  });
  return `// SPDX-License-Identifier: GPL-3.0-or-later. Part of the QuadMath simulator; see SIM-NOTICE.txt.
// The Rig's coach lines (sim-coach.js RIG_COURSES), flown on the bf core
// (sim-core ${coreVersion}, the Air65 on the owner's diff, the Rig's contact
// plant) by the autopilot of tools/coach_rig_pilot.mjs, from each drill's pad
// (drillSpawn), armed in angle mode, the sticks polled every 4 ms.
//   ms      lift-off (0.1 m off the pad) to the last gate, rounded up: gold,
//           and silver 1.3x, bronze 1.7x (sim-coach.js medalTimes);
//   splits  each gate, ms from lift-off;
//   line    the ghost ribbon: [ms from lift-off, x, y, z], world units.
// Generated by tools/fly_coach_rig.mjs --write. Do not edit by hand.
export const RIG_LINES_CORE = '${coreVersion}';
export const RIG_LINES = Object.freeze({
${rows.join('\n')}
});
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const all = await flyAll();
  for (const [id, { line }] of Object.entries(all)) {
    console.log(id.padEnd(14), (line.ms / 1000).toFixed(3) + ' s', 'splits', line.splits.map((s) => (s / 1000).toFixed(2)).join(' '), line.line.length + ' ribbon points');
  }
  if (process.argv.includes('--write')) {
    const lines = Object.fromEntries(Object.entries(all).map(([id, v]) => [id, v.line]));
    writeFileSync(join(root, 'sim-coach-lines.js'), moduleText(lines));
    console.log('wrote sim-coach-lines.js');
  }
}
